import cv2
import numpy as np
import matplotlib.pyplot as plt

# Load the video
video = cv2.VideoCapture('harris_corner_detection_image_V.mp4')

# Harris Corner Detection parameters
blockSize = 3
apertureSize = 3
k = 0.06
threshold = 0.05

# Get video properties
fps = video.get(cv2.CAP_PROP_FPS)
width = int(video.get(cv2.CAP_PROP_FRAME_WIDTH))
height = int(video.get(cv2.CAP_PROP_FRAME_HEIGHT))

# Create output video
fourcc = cv2.VideoWriter_fourcc(*'mp4v')
out = cv2.VideoWriter('Harris_Video.mp4', fourcc, fps, (width, height))

# Process all video frames
while True:
    ret, frame = video.read()

    if not ret:
        break

    # Convert to grayscale
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

    # Apply Gaussian Blur
    gray = cv2.GaussianBlur(gray, (5, 5), 0)

    # Harris Corner Detection
    corners = cv2.cornerHarris(gray, blockSize, apertureSize, k)

    # Non-Maximum Suppression
    local_max = cv2.dilate(corners, None)

    # Apply threshold and NMS
    mask = (corners > threshold * corners.max()) & (corners == local_max)

    # Draw red circles around detected corners
    y, x = np.where(mask)

    for a, b in zip(x, y):
        cv2.circle(frame, (a, b), 3, (0, 0, 255), 1)

    # Save processed frame
    out.write(frame)

# Release video files
video.release()
out.release()